/**
 * Generates src/components/icons/phosphor-paths.ts: just the Phosphor (duotone) icons the
 * app uses, as path data, so we don't ship the whole 1,500-icon library.
 *
 *   npm install --no-save @phosphor-icons/core@2.1.1
 *   node scripts/make-icon-data.js
 *
 * Phosphor Icons are MIT licensed (https://phosphoricons.com). Add a name to ICONS to use
 * another one.
 */
const fs = require('fs');
const path = require('path');

const ICONS = [
  'arrows-clockwise', 'baby', 'bell', 'bowl-food', 'calendar-blank', 'camera', 'caret-left',
  'caret-right', 'chart-bar', 'check', 'clock', 'clock-counter-clockwise', 'download-simple',
  'drop', 'file-csv', 'gear', 'house', 'map-pin', 'moon', 'moon-stars', 'pencil-simple',
  'pill', 'plus', 'qr-code', 'ruler', 'scales', 'sparkle', 'sun', 'sun-horizon', 'timer',
  'trash', 'upload-simple', 'users-three', 'warning', 'wifi-high', 'x',
];

// The package doesn't export package.json, so look for it along the module search paths.
const root = require.resolve
  .paths('@phosphor-icons/core')
  .map((dir) => path.join(dir, '@phosphor-icons/core'))
  .find((dir) => fs.existsSync(path.join(dir, 'assets/duotone')));
if (!root) throw new Error('Install @phosphor-icons/core first (see the comment at the top).');
const out = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(root, 'assets/duotone', `${name}-duotone.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"( opacity="0.2")?\/>/g)];
  if (paths.length === 0) throw new Error(`${name}: no paths found`);
  out[name] = {
    duo: paths.filter((p) => p[2]).map((p) => p[1]),
    solid: paths.filter((p) => !p[2]).map((p) => p[1]),
  };
}

const target = path.join(__dirname, '../src/components/icons/phosphor-paths.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(
  target,
  `// Generated by scripts/make-icon-data.js from @phosphor-icons/core (MIT,
// https://phosphoricons.com) — do not edit by hand.
// Each icon: \`duo\` = the soft background shape (drawn at 20% opacity), \`solid\` = the outline.

export const PHOSPHOR = ${JSON.stringify(out, null, 2)} as const;

export type PhosphorName = keyof typeof PHOSPHOR;
`,
);
console.log(`wrote ${ICONS.length} icons to ${path.relative(process.cwd(), target)}`);
